#!/usr/bin/env python3
"""Reproduce the deliberately public, fixed 1–100 graph; never serve this script."""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from aliquot.orbit_graph import build_orbit_graph  # noqa: E402

OUTPUT = ROOT / "site/orbit-data.js"


def render(data):
    # One record per line keeps the small generated artifact reviewable.
    lines = ["'use strict';", "// Generated by python3 scripts/build_orbit_graph.py; do not edit.",
             "const AliquotOrbitData = {"]
    entries = list(data.items())
    for index, (key, value) in enumerate(entries):
        suffix = "," if index < len(entries) - 1 else ""
        if isinstance(value, list):
            lines.append(f'  "{key}": [')
            lines.extend("    " + json.dumps(record, separators=(",", ":")) +
                         ("," if i < len(value) - 1 else "") for i, record in enumerate(value))
            lines.append("  ]" + suffix)
        else:
            lines.append(f'  "{key}": ' + json.dumps(value, separators=(",", ":")) + suffix)
    return "\n".join(lines + ["};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed data is stale; write nothing.")
    args = parser.parse_args()
    expected = render(build_orbit_graph())
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
            print("Orbit data is stale: run python3 scripts/build_orbit_graph.py", file=sys.stderr)
            return 1
    else:
        OUTPUT.write_text(expected)
        print("Updated site/orbit-data.js; refresh asset hashes next.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
